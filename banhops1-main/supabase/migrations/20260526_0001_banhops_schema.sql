do $$
begin
  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'locations' and policyname = 'locations are readable by everyone'
  ) then
    create policy "locations are readable by everyone"
      on public.locations
      for select
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'users' and policyname = 'users can read their profile'
  ) then
    create policy "users can read their profile"
      on public.users
      for select
      using (auth.uid() = id);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'users' and policyname = 'users can update their profile'
  ) then
    create policy "users can update their profile"
      on public.users
      for update
      using (auth.uid() = id)
      with check (auth.uid() = id);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'trips' and policyname = 'users manage their trips'
  ) then
    create policy "users manage their trips"
      on public.trips
      for all
      using (auth.uid() = user_id)
      with check (auth.uid() = user_id);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'routes' and policyname = 'routes follow trip ownership'
  ) then
    create policy "routes follow trip ownership"
      on public.routes
      for all
      using (exists (select 1 from public.trips t where t.id = trip_id and t.user_id = auth.uid()))
      with check (exists (select 1 from public.trips t where t.id = trip_id and t.user_id = auth.uid()));
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'chats' and policyname = 'chats belong to current user'
  ) then
    create policy "chats belong to current user"
      on public.chats
      for all
      using (auth.uid() = user_id)
      with check (auth.uid() = user_id);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'microbuses' and policyname = 'microbuses are readable by everyone'
  ) then
    create policy "microbuses are readable by everyone"
      on public.microbuses
      for select
      using (true);
  end if;

  if not exists (
    select 1 from pg_policies where schemaname = 'public' and tablename = 'trains' and policyname = 'trains are readable by everyone'
  ) then
    create policy "trains are readable by everyone"
      on public.trains
      for select
      using (true);
  end if;
end $$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (id, name)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'name', new.raw_user_meta_data->>'full_name', new.email, 'BanHops Rider')
  )
  on conflict (id) do update
    set name = excluded.name;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();